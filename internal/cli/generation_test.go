func TestGenerateProject_whenGeneratedContentChanges_shouldReplaceExistingFile(t *testing.T) {
	root := writeTestModule(t, map[string]string{
		"go.mod": "module example.com/app\n\ngo 1.25\n",
		"app/wiring.go": `package app

//goark:service
type UserService struct{}
`,
	})
	project, err := newTestProjectResolver(root).Resolve()
	if err != nil {
		t.Fatalf("发现项目失败: %v", err)
	}
	if _, err := generateProject(project, false); err != nil {
		t.Fatalf("首次生成失败: %v", err)
	}
	if err := os.WriteFile(filepath.Join(root, "app", "wiring.go"), []byte(`package app

//goark:service
type OrderService struct{}
`), 0o644); err != nil {
		t.Fatalf("修改源码失败: %v", err)
	}

	results, err := generateProject(project, false)
	if err != nil {
		t.Fatalf("替换生成文件失败: %v", err)
	}
	if len(results) != 1 || !results[0].Changed {
		t.Fatalf("替换结果错误: %#v", results)
	}
	data, err := os.ReadFile(results[0].Output)
	if err != nil {
		t.Fatalf("读取生成文件失败: %v", err)
	}
	if !strings.Contains(string(data), "orderService") || strings.Contains(string(data), "userService") {
		t.Fatalf("生成内容未替换:\n%s", data)
	}
}

