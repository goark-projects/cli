func TestGenerateProject_whenInvokedConcurrently_shouldProduceCompleteSource(t *testing.T) {
	root := writeTestModule(t, map[string]string{
		"go.mod": "module example.com/app\n\ngo 1.25\n",
		"app/wiring.go": `package app

//goark:service
type UserService struct{}
`,
	})
	project, err := newTestProjectResolver(root).Resolve()
	if err != nil {
		t.Fatalf("发现项目失败: %v", err)
	}

	start := make(chan struct{})
	errorsFound := make(chan error, 8)
	var group sync.WaitGroup
	for range 8 {
		group.Add(1)
		go func() {
			defer group.Done()
			<-start
			_, generateErr := generateProject(project, false)
			errorsFound <- generateErr
		}()
	}
	close(start)
	group.Wait()
	close(errorsFound)
	for generateErr := range errorsFound {
		if generateErr != nil {
			t.Fatalf("并发生成失败: %v", generateErr)
		}
	}
	data, err := os.ReadFile(filepath.Join(root, "app", "zz_goark_app_gen.go"))
	if err != nil {
		t.Fatalf("读取并发生成文件失败: %v", err)
	}
	if !containsAll(string(data), "Code generated by goark", "type GoarkPackageConfiguration struct{}", "userService") {
		t.Fatalf("并发生成内容不完整:\n%s", data)
	}
}

