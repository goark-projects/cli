func TestGenerateProject_whenAnnotatedPackageExists_shouldWriteDeterministicSource(t *testing.T) {
	root := writeTestModule(t, map[string]string{
		"go.mod": "module example.com/app\n\ngo 1.25\n",
		"internal/app/wiring.go": `package app

//goark:service
type UserService struct{}
`,
	})
	project, err := newTestProjectResolver(root).Resolve()
	if err != nil {
		t.Fatalf("发现项目失败: %v", err)
	}

	results, err := generateProject(project, false)
	if err != nil {
		t.Fatalf("生成项目失败: %v", err)
	}
	if len(results) != 1 || !results[0].Changed {
		t.Fatalf("生成结果错误: %#v", results)
	}
	output := filepath.Join(root, "internal", "app", "zz_goark_app_gen.go")
	data, err := os.ReadFile(output)
	if err != nil {
		t.Fatalf("读取生成文件失败: %v", err)
	}
	if !containsAll(string(data), "Code generated by goark", "type GoarkPackageConfiguration struct{}", "userService") {
		t.Fatalf("生成内容错误:\n%s", data)
	}

	oldTime := time.Unix(1_700_000_000, 0)
	if err := os.Chtimes(output, oldTime, oldTime); err != nil {
		t.Fatalf("设置文件时间失败: %v", err)
	}
	results, err = generateProject(project, false)
	if err != nil {
		t.Fatalf("重复生成项目失败: %v", err)
	}
	if len(results) != 1 || !results[0].Changed {
		t.Fatalf("每次生成都应覆盖目标文件: %#v", results)
	}
	info, err := os.Stat(output)
	if err != nil {
		t.Fatalf("读取生成文件状态失败: %v", err)
	}
	if info.ModTime().Equal(oldTime) {
		t.Fatalf("生成文件未被覆盖: %v", info.ModTime())
	}
}

