package scaffold

import "strconv"

func appFiles(spec appSpec) []fileSpec {
	files := []fileSpec{
		{path: ".gitignore", content: gitignoreTemplate()},
		{path: "goark.build", content: goarkBuildTemplate(spec)},
	}
	if spec.projectType == ProjectTypeApp {
		return append(files,
			fileSpec{path: "README.md", content: applicationReadmeTemplate(spec)},
			fileSpec{path: "go.mod", content: applicationGoModTemplate(spec)},
			fileSpec{path: "resource/app.yml", content: applicationConfigTemplate(spec)},
			fileSpec{path: "cmd/app/main.go", content: minimalMainTemplate()},
			fileSpec{path: "cmd/app/goark.go", content: applicationGoarkTemplate(spec)},
			fileSpec{path: "internal/app/configuration.go", content: applicationConfigurationTemplate(spec)},
		)
	}
	return append(files,
		fileSpec{path: "README.md", content: webReadmeTemplate(spec)},
		fileSpec{path: "go.mod", content: webGoModTemplate(spec)},
		fileSpec{path: "resource/app.yml", content: webConfigTemplate(spec)},
		fileSpec{path: "resource/static/index.html", content: staticIndexTemplate(spec)},
		fileSpec{path: "cmd/server/main.go", content: minimalMainTemplate()},
		fileSpec{path: "cmd/server/goark.go", content: webGoarkTemplate(spec)},
		fileSpec{path: "internal/app/configuration.go", content: webConfigurationTemplate()},
	)
}

func minimalMainTemplate() string {
	return `package main

import "os"

func main() {
	os.Exit(runGoark(os.Args[1:]))
}
`
}

func goarkBuildTemplate(spec appSpec) string {
	mainPackage := "./cmd/app"
	if spec.projectType == ProjectTypeWeb {
		mainPackage = "./cmd/server"
	}
	return `# Goark 项目构建描述文件
version = 1

[project]
name = ` + strconv.Quote(spec.name) + `
main = ` + strconv.Quote(mainPackage) + `

[commands.build]
go-args = ["-trimpath"]
output = "./build/` + spec.name + `"

[commands.test]
go-args = ["./..."]
`
}

